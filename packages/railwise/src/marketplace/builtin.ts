function skill(item: (typeof skills)[number]): CapabilityManifest {
  return {
    id: `railwise.skill.${item.id}`,
    kind: "skill",
    name: item.name,
    description: item.description,
    version: "0.1.0",
    source: "builtin",
    enabled: true,
    installed: true,
    permissions: item.permissions,
    tags: item.tags,
  }
}

